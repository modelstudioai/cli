function serializeTranslations(): string {
  return JSON.stringify(
    [...ZH_CN_REPLACEMENTS].sort(([englishA], [englishB]) => englishB.length - englishA.length),
  ).replaceAll("<", "\\u003c");
}

export function renderConfigUiShell(html: string, language: Language): string {
  return html
    .replace('<html lang="en">', `<html lang="${language}">`)
    .replace("__BL_CONFIG_UI_LANGUAGE__", language)
    .replace("__BL_CONFIG_UI_TRANSLATIONS__", serializeTranslations());
}
